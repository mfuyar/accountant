-- Green Fort normalized project-cost ledger foundation.
-- Existing cost_versions remain the immutable source of truth; these fields add
-- separate cost-purpose and funding dimensions without changing old totals.

alter table public.owners
  add column if not exists ownership_percentage numeric(7,4),
  add column if not exists is_active boolean not null default true;

alter table public.cost_versions
  add column if not exists vendor_name text,
  add column if not exists main_category text,
  add column if not exists subcategory text,
  add column if not exists payer_type text,
  add column if not exists payer_owner_id bigint references public.owners(id) on delete set null,
  add column if not exists payer_name text,
  add column if not exists payment_source text,
  add column if not exists reference_number text,
  add column if not exists reimbursable boolean not null default false,
  add column if not exists loan_related boolean not null default false,
  add column if not exists notes text,
  add column if not exists recurring_frequency text,
  add column if not exists is_soft_cost_parent boolean not null default false;

alter table public.cost_versions drop constraint if exists cost_versions_payer_type_check;
alter table public.cost_versions add constraint cost_versions_payer_type_check
  check (payer_type is null or payer_type in ('owner', 'company', 'construction_loan', 'other_company', 'third_party'));
alter table public.cost_versions drop constraint if exists cost_versions_recurring_frequency_check;
alter table public.cost_versions add constraint cost_versions_recurring_frequency_check
  check (recurring_frequency is null or recurring_frequency in ('monthly', 'quarterly', 'annual'));

create table if not exists public.properties (
  id bigint generated by default as identity primary key,
  company_id uuid not null references public.companies(id) on delete cascade,
  project_id bigint references public.projects(id) on delete set null,
  address text not null,
  parcel_number text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cost_subcategories (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.cost_categories(id) on delete cascade,
  name text not null,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  unique (category_id, name)
);

create table if not exists public.funding_sources (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  source_type text not null check (source_type in ('owner', 'company', 'construction_loan', 'other_company', 'third_party')),
  owner_id bigint references public.owners(id) on delete set null,
  name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.loans (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  funding_source_id bigint references public.funding_sources(id) on delete set null,
  lender_name text not null,
  loan_name text,
  account_last_four text,
  original_principal numeric(14,2),
  interest_rate numeric(9,6),
  start_date date,
  maturity_date date,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.transaction_allocations (
  id bigint generated by default as identity primary key,
  transaction_id bigint references public.transactions(id) on delete cascade,
  cost_id uuid,
  project_id bigint references public.projects(id) on delete cascade,
  allocation_percentage numeric(7,4),
  allocation_amount numeric(14,2) not null,
  created_at timestamptz not null default now(),
  check (allocation_percentage is null or allocation_percentage between 0 and 100),
  check (allocation_amount >= 0),
  check (transaction_id is not null or cost_id is not null)
);

create table if not exists public.ledger_audit_logs (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  cost_id uuid,
  action text not null check (action in ('create', 'update', 'archive', 'restore')),
  old_values jsonb,
  new_values jsonb,
  changed_by uuid references auth.users(id) on delete set null default auth.uid(),
  changed_at timestamptz not null default now()
);

create index if not exists cost_versions_project_main_category_idx on public.cost_versions(project_id, main_category);
create index if not exists cost_versions_project_payer_idx on public.cost_versions(project_id, payer_type, payer_owner_id);
create index if not exists funding_sources_project_idx on public.funding_sources(project_id);
create index if not exists loans_project_idx on public.loans(project_id);
create index if not exists transaction_allocations_project_idx on public.transaction_allocations(project_id);
create index if not exists ledger_audit_logs_cost_idx on public.ledger_audit_logs(project_id, cost_id, changed_at desc);

