create or replace function public.create_cost_version_v8(
  p_project_id bigint, p_cost_id uuid, p_parent_cost_id uuid, p_owner_id bigint,
  p_name text, p_amount numeric, p_phase text, p_category text,
  p_lot_allocations jsonb, p_cost_date date, p_attachments jsonb default '[]'::jsonb,
  p_deleted boolean default false, p_details text default null,
  p_construction_draft_id uuid default null, p_payment_method text default null,
  p_payment_fee_percentage numeric default null, p_payment_fee_amount numeric default null,
  p_payment_date date default null, p_invoice_amount numeric default null,
  p_vendor_name text default null, p_main_category text default null,
  p_subcategory text default null, p_payer_type text default null,
  p_payer_owner_id bigint default null, p_payer_name text default null,
  p_payment_source text default null, p_reference_number text default null,
  p_reimbursable boolean default false, p_loan_related boolean default false,
  p_notes text default null, p_recurring_frequency text default null,
  p_is_soft_cost_parent boolean default false
) returns public.cost_versions
language plpgsql security invoker set search_path = '' as $$
declare
  next_version integer;
  allocation_total numeric;
  prior_row public.cost_versions;
  result public.cost_versions;
begin
  if not private.can_manage_project(p_project_id) then raise exception 'You do not have permission to manage this project'; end if;
  if p_amount < 0 then raise exception 'Amount cannot be negative'; end if;
  if p_payment_fee_percentage is not null and (p_payment_fee_percentage < 0 or p_payment_fee_percentage > 100) then raise exception 'Payment fee percentage must be between 0 and 100'; end if;
  if jsonb_typeof(coalesce(p_lot_allocations, '[]'::jsonb)) <> 'array' then raise exception 'Lot allocations must be an array'; end if;
  select coalesce(sum((item->>'amount')::numeric), 0) into allocation_total from jsonb_array_elements(coalesce(p_lot_allocations, '[]'::jsonb)) item;
  if jsonb_array_length(coalesce(p_lot_allocations, '[]'::jsonb)) > 0 and abs(allocation_total - p_amount) > 0.009 then raise exception 'Lot allocations must equal the total cost amount'; end if;
  if p_parent_cost_id is not null and not exists (select 1 from public.cost_versions where project_id = p_project_id and cost_id = p_parent_cost_id) then raise exception 'The parent cost does not exist in this project'; end if;

  perform pg_advisory_xact_lock(hashtextextended(p_cost_id::text, 0));
  select * into prior_row from public.cost_versions where project_id = p_project_id and cost_id = p_cost_id order by version desc limit 1;
  select coalesce(max(version), 0) + 1 into next_version from public.cost_versions where cost_id = p_cost_id and project_id = p_project_id;

  insert into public.cost_versions (
    cost_id, parent_cost_id, project_id, owner_id, version, name, details,
    construction_draft_id, payment_method, payment_fee_percentage, payment_fee_amount,
    payment_date, invoice_amount, amount, phase, category, lot_allocations, cost_date,
    attachments, deleted_at, vendor_name, main_category, subcategory, payer_type,
    payer_owner_id, payer_name, payment_source, reference_number, reimbursable,
    loan_related, notes, recurring_frequency, is_soft_cost_parent
  ) values (
    p_cost_id, p_parent_cost_id, p_project_id, p_owner_id, next_version, trim(p_name), nullif(trim(p_details), ''),
    p_construction_draft_id, nullif(trim(p_payment_method), ''), p_payment_fee_percentage, p_payment_fee_amount,
    p_payment_date, p_invoice_amount, p_amount, p_phase, nullif(trim(p_category), ''), coalesce(p_lot_allocations, '[]'::jsonb), p_cost_date,
    coalesce(p_attachments, '[]'::jsonb), case when p_deleted then now() else null end,
    nullif(trim(p_vendor_name), ''), nullif(trim(p_main_category), ''), nullif(trim(p_subcategory), ''), p_payer_type,
    p_payer_owner_id, nullif(trim(p_payer_name), ''), nullif(trim(p_payment_source), ''), nullif(trim(p_reference_number), ''),
    coalesce(p_reimbursable, false), coalesce(p_loan_related, false), nullif(trim(p_notes), ''), p_recurring_frequency,
    coalesce(p_is_soft_cost_parent, false)
  ) returning * into result;

  insert into public.ledger_audit_logs(project_id, cost_id, action, old_values, new_values)
  values (p_project_id, p_cost_id,
    case when p_deleted then 'archive' when prior_row.id is null then 'create' else 'update' end,
    case when prior_row.id is null then null else to_jsonb(prior_row) end, to_jsonb(result));
  return result;
end;
$$;

